const { test, expect } = require('@playwright/test');
const { execFileSync } = require('node:child_process');
const BASE = process.env.BASE_URL || 'http://127.0.0.1:8000';
const fixture = (script, action, ...args) => execFileSync('php', [`tests/${script}.php`, action, ...args.map(String)], { encoding: 'utf8' }).trim();

test('podium voting on mobile, all-player Goodfellas, weighted publication and admin editing', async ({ page, context }) => {
  test.setTimeout(60000);
  const data = JSON.parse(fixture('live-matches-fixture', 'create', 3));
  const setup = JSON.parse(fixture('award-podium-fixture', 'setup', data.id));
  const cookie = JSON.parse(fixture('live-matches-fixture', 'director-session', data.id));
  const value = (p) => `${p.name} (#${p.id})`;
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  try {
    await context.addCookies([{ ...cookie, url: BASE }]);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${BASE}/junta_votaciones.php?match_id=${data.id}`);
    const select = (label) => page.getByRole('combobox', { name: label, exact: true });
    await select('Elegir jugador para Pase magistral - 1').selectOption(value(data.players[0]));
    await page.getByRole('button', { name: 'Agregar 2.º puesto a Pase magistral', exact: true }).click();
    await select('Elegir jugador para Pase magistral - 2').selectOption(value(data.players[1]));
    await page.getByRole('button', { name: 'Agregar 3.º puesto a Pase magistral', exact: true }).click();
    await select('Elegir jugador para Pase magistral - 3').selectOption(value(data.players[2]));
    await expect(page.locator('#award-masterful_pass-3')).toHaveValue(value(data.players[2]));
    await page.getByRole('button', { name: 'Subir puesto 3 de Pase magistral', exact: true }).click();
    await expect(page.locator('#award-masterful_pass-2')).toHaveValue(value(data.players[2]));
    await expect(select('Elegir jugador para Pase magistral - 3').locator('option', { hasText: data.players[0].name })).toBeDisabled();
    await expect(page.locator('[name="awards[player_of_match][0]"]')).toHaveCount(1);
    await expect(page.getByRole('button', { name: /Agregar .* puesto a Man of the Match/ })).toHaveCount(0);
    await select('Elegir jugador para Man of the Match').selectOption(value(data.players[0]));
    await select('Elegir jugador para Goodfellas - 1').selectOption(value(setup.outsiders[0]));
    await page.getByRole('button', { name: 'Agregar 2.º puesto a Goodfellas', exact: true }).click();
    await select('Elegir jugador para Goodfellas - 2').selectOption(value(setup.outsiders[1]));
    await expect(select('Elegir jugador para Pase magistral - 1').locator('option', { hasText: setup.outsiders[0].name })).toHaveCount(0);
    const masterful = page.locator('fieldset').filter({ has: page.locator('#award-masterful_pass') });
    await masterful.screenshot({ path: 'outputs/award-podium-mobile.png' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    page.on('dialog', (dialog) => dialog.accept());
    await page.getByRole('button', { name: 'Enviar voto', exact: true }).click();
    await page.waitForURL(/vote_saved=1/);
    await page.goto(`${BASE}/junta_votaciones.php?match_id=${data.id}`);
    await expect(page.locator('#award-masterful_pass-2')).toHaveValue(value(data.players[2]));
    await expect(page.locator('#award-goodfellas-2')).toHaveValue(value(setup.outsiders[1]));
    expect(fixture('award-podium-fixture', 'rules', data.id)).toContain('OK:');
    await page.goto(`${BASE}/junta_votaciones.php?match_id=${data.id}`);
    await expect(page.getByRole('heading', { name: 'Premios', exact: true })).toBeVisible();
    await expect(page.locator('ol').filter({ hasText: data.players[1].name }).first()).toBeVisible();
    await context.clearCookies();
    await page.goto(`${BASE}/login.php?next=editar_partidos.php`);
    await page.getByRole('button', { name: 'Administrador', exact: true }).click();
    await page.locator('#adminPassword').fill(process.env.GOODFELLAS_ADMIN_PASSWORD || 'Goodfellas2026');
    await page.getByRole('button', { name: 'Entrar como admin', exact: true }).click();
    await page.waitForURL('**/editar_partidos.php');
    await page.goto(`${BASE}/finalizar_partido.php?match_id=${data.id}&edit_details=1`);
    await page.locator('#valoraciones > summary').click();
    await expect(page.locator('#award-masterful_pass-3')).toBeVisible();
    await expect(page.locator('#award-goodfellas').getAttribute('list')).resolves.toBe('allAwardPlayers');
    await page.locator('#award-masterful_pass-2').fill('');
    await page.locator('#award-masterful_pass-3').fill('');
    await page.getByRole('button', { name: 'Guardar premios', exact: true }).click();
    await page.waitForURL(/edit_details=1/);
    await expect.poll(() => JSON.parse(fixture('live-matches-fixture', 'inspect', data.id)).awards.masterful_pass.podium.length).toBe(1);
    const exportResponse = await page.request.get(`${BASE}/exportar_fecha.php?match_id=${data.id}`);
    const csv = await exportResponse.text();
    expect(csv).toContain('Puesto');
    expect(csv).toContain(setup.outsiders[0].name);
    await context.clearCookies();
    await context.addCookies([{ ...setup.profileCookie, url: BASE }]);
    await page.goto(`${BASE}/perfil.php`);
    await expect(page.locator('.profile-award-chip').filter({ hasText: 'Goodfellas' })).toContainText('1.º: 1');
    expect(errors).toEqual([]);
  } finally { fixture('live-matches-fixture', 'delete', data.id); }
});
